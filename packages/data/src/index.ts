function 创建行政区记录(
  编码: string,
  名称: string,
  拼音: string,
  首字母: string,
  级别: 城市["级别"],
  父级编码?: string,
  省份名称?: string,
): 城市 {
  return {
    编码,
    名称,
    拼音,
    首字母,
    级别,
    父级编码,
    省份名称,
    国家代码: "CN",
  }
}

function 校验记录列表(
  记录列表: readonly 城市[],
  来源: string,
  问题列表: 数据校验问题[],
): void {
  const 已见编码 = new Set<string>()

  for (const 记录 of 记录列表) {
    if (已见编码.has(记录.编码)) {
      问题列表.push({
        代码: "重复编码",
        编码: 记录.编码,
        消息: `编码 ${记录.编码} 重复`,
      })
    }
    已见编码.add(记录.编码)

    if (记录.名称.trim() === "") {
      问题列表.push({
        代码: "名称为空",
        编码: 记录.编码,
        消息: `${来源} 记录 ${记录.编码} 名称为空`,
      })
    }

    if (!["省", "市", "区县"].includes(记录.级别)) {
      问题列表.push({
        代码: "级别非法",
        编码: 记录.编码,
        消息: `${记录.名称} 的级别 ${记录.级别} 非法`,
      })
    }

    if ((记录.拼音 ?? "").trim() === "") {
      问题列表.push({
        代码: "缺少拼音",
        编码: 记录.编码,
        消息: `${记录.名称} 缺少拼音`,
      })
    }

    if ((记录.首字母 ?? "").trim() === "") {
      问题列表.push({
        代码: "缺少首字母",
        编码: 记录.编码,
        消息: `${记录.名称} 缺少首字母`,
      })
    }
  }
}

function 校验行政区父级(行政区列表: readonly 城市[], 问题列表: 数据校验问题[]): void {
  const 行政区编码 = new Set(行政区列表.map((记录) => 记录.编码))

  for (const 记录 of 行政区列表) {
    if (记录.级别 === "省") {
      continue
    }

    if (!记录.父级编码 || !行政区编码.has(记录.父级编码)) {
      问题列表.push({
        代码: "父级缺失",
        编码: 记录.编码,
        消息: `${记录.名称} 的父级编码 ${记录.父级编码 ?? "(空)"} 不存在`,
      })
    }
  }
}

function 校验热门城市(
  城市列表: readonly 城市[],
  热门编码列表: readonly string[],
  问题列表: 数据校验问题[],
): void {
  const 城市编码 = new Set(城市列表.map((记录) => 记录.编码))

  for (const 热门编码 of 热门编码列表) {
    if (!城市编码.has(热门编码)) {
      问题列表.push({
        代码: "热门城市缺失",
        编码: 热门编码,
        消息: `热门城市编码 ${热门编码} 不存在于城市列表`,
      })
    }
  }
}
